#include <openssl/evp.h>
#include <openssl/rand.h>
#include <openssl/crypto.h>

#include <algorithm>
#include <array>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

namespace fs = std::filesystem;
static constexpr std::array<unsigned char, 4> MAGIC{'N','S','C','R'};
static constexpr unsigned char VERSION = 1;
static constexpr std::size_t KEY_SIZE = 32, NONCE_SIZE = 12, TAG_SIZE = 16;

struct Task {
    bool encrypt;
    fs::path source;
    fs::path destination;
};

static void require(bool ok, const std::string& message) {
    if (!ok) throw std::runtime_error(message);
}

static std::vector<unsigned char> read_all(const fs::path& p) {
    std::ifstream in(p, std::ios::binary);
    require(in.good(), "cannot open input: " + p.string());
    return {std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()};
}

static void write_all(const fs::path& p, const std::vector<unsigned char>& bytes) {
    if (!p.parent_path().empty()) fs::create_directories(p.parent_path());
    std::ofstream out(p, std::ios::binary | std::ios::trunc);
    require(out.good(), "cannot create output: " + p.string());
    if (!bytes.empty())
        out.write(reinterpret_cast<const char*>(bytes.data()), static_cast<std::streamsize>(bytes.size()));
    require(out.good(), "write failed: " + p.string());
}

static std::array<unsigned char, KEY_SIZE> random_key() {
    std::array<unsigned char, KEY_SIZE> key{};
    require(RAND_bytes(key.data(), static_cast<int>(key.size())) == 1, "OpenSSL RAND_bytes failed");
    return key;
}

static std::vector<unsigned char> encrypt_bytes(
    const std::vector<unsigned char>& plain,
    const std::array<unsigned char, KEY_SIZE>& key) {

    std::array<unsigned char, NONCE_SIZE> nonce{};
    require(RAND_bytes(nonce.data(), static_cast<int>(nonce.size())) == 1, "nonce generation failed");

    EVP_CIPHER_CTX* ctx = EVP_CIPHER_CTX_new();
    require(ctx != nullptr, "EVP_CIPHER_CTX_new failed");

    std::vector<unsigned char> ciphertext(plain.size() + 16);
    int len = 0, total = 0;
    bool ok =
        EVP_EncryptInit_ex(ctx, EVP_aes_256_gcm(), nullptr, nullptr, nullptr) == 1 &&
        EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_SET_IVLEN, static_cast<int>(nonce.size()), nullptr) == 1 &&
        EVP_EncryptInit_ex(ctx, nullptr, nullptr, key.data(), nonce.data()) == 1;

    if (ok && !plain.empty()) {
        ok = EVP_EncryptUpdate(ctx, ciphertext.data(), &len, plain.data(),
                               static_cast<int>(plain.size())) == 1;
        total = len;
    }
    if (ok) {
        ok = EVP_EncryptFinal_ex(ctx, ciphertext.data() + total, &len) == 1;
        total += len;
    }

    std::array<unsigned char, TAG_SIZE> tag{};
    if (ok)
        ok = EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_GET_TAG,
                                 static_cast<int>(tag.size()), tag.data()) == 1;
    EVP_CIPHER_CTX_free(ctx);
    require(ok, "AES-256-GCM encryption failed");

    std::vector<unsigned char> output;
    output.reserve(5 + NONCE_SIZE + TAG_SIZE + static_cast<std::size_t>(total));
    output.insert(output.end(), MAGIC.begin(), MAGIC.end());
    output.push_back(VERSION);
    output.insert(output.end(), nonce.begin(), nonce.end());
    output.insert(output.end(), tag.begin(), tag.end());
    output.insert(output.end(), ciphertext.begin(), ciphertext.begin() + total);
    return output;
}

static void emit_rust_key(const fs::path& path,
                          const std::array<unsigned char, KEY_SIZE>& key) {
    if (!path.parent_path().empty()) fs::create_directories(path.parent_path());
    std::ofstream out(path, std::ios::trunc);
    require(out.good(), "cannot write Rust key: " + path.string());

    out << "// Generated by the C++ resource packer. Do not edit or commit.\n";
    for (int part = 0; part < 4; ++part) {
        out << "pub const KEY_PART_" << part << ": [u8; 8] = [";
        for (int i = 0; i < 8; ++i) {
            if (i) out << ", ";
            out << static_cast<unsigned>(key[part * 8 + i]);
        }
        out << "];\n";
    }
    out << "pub fn key_bytes() -> [u8; 32] {\n"
           "    [KEY_PART_0, KEY_PART_1, KEY_PART_2, KEY_PART_3]"
           ".concat().try_into().expect(\"key length\")\n}\n";
    require(out.good(), "failed writing Rust key");
}

static std::vector<Task> parse_manifest(const fs::path& manifest) {
    std::ifstream in(manifest);
    require(in.good(), "cannot open manifest: " + manifest.string());
    std::vector<Task> tasks;
    std::string line;
    std::size_t line_no = 0;

    while (std::getline(in, line)) {
        ++line_no;
        auto first = line.find_first_not_of(" \\t\\r");
        if (first == std::string::npos || line[first] == '#') continue;

        std::istringstream row(line);
        std::string mode, src, dst, extra;
        row >> mode >> std::quoted(src) >> std::quoted(dst);
        require(!row.fail() && !(row >> extra),
                "invalid manifest syntax at line " + std::to_string(line_no));
        fs::path source = src;
        fs::path destination = dst;

        require(mode == "encrypt" || mode == "copy",
                "mode must be 'encrypt' or 'copy' at manifest line " + std::to_string(line_no));
        require(!source.empty() && !destination.empty(),
                "empty source/destination at manifest line " + std::to_string(line_no));
        tasks.push_back({mode == "encrypt", source, destination});
    }
    require(!tasks.empty(), "manifest contains no tasks");
    return tasks;
}

static void process_task(const Task& task,
                         const std::array<unsigned char, KEY_SIZE>* key) {
    require(fs::exists(task.source) && fs::is_directory(task.source),
            "source directory does not exist: " + task.source.string());
    require(task.source != task.destination,
            "source and destination must differ: " + task.source.string());

    if (fs::exists(task.destination)) fs::remove_all(task.destination);
    fs::create_directories(task.destination);

    for (const auto& entry : fs::recursive_directory_iterator(task.source)) {
        const auto relative = fs::relative(entry.path(), task.source);
        const auto target = task.destination / relative;

        if (entry.is_directory()) {
            fs::create_directories(target);
        } else if (entry.is_regular_file()) {
            if (task.encrypt) {
                require(key != nullptr, "internal error: encryption key unavailable");
                auto plain = read_all(entry.path());
                auto encrypted = encrypt_bytes(plain, *key);
                write_all(target, encrypted);
                if (!plain.empty()) OPENSSL_cleanse(plain.data(), plain.size());
            } else {
                fs::create_directories(target.parent_path());
                fs::copy_file(entry.path(), target, fs::copy_options::overwrite_existing);
            }
            std::cout << (task.encrypt ? "encrypted: " : "copied: ")
                      << entry.path().string() << " -> " << target.string() << "\n";
        }
    }
}

int main(int argc, char** argv) {
    try {
        fs::path manifest, key_out, key_tmp;
        for (int i = 1; i < argc; ++i) {
            const std::string arg = argv[i];
            if (arg.rfind("--manifest=", 0) == 0) manifest = arg.substr(11);
            else if (arg.rfind("--key-out=", 0) == 0) key_out = arg.substr(10);
            else if (arg.rfind("--key-tmp=", 0) == 0) key_tmp = arg.substr(10);
            else throw std::runtime_error("unknown argument: " + arg);
        }
        require(!manifest.empty(), "usage: crypto --manifest=resources.conf --key-out=key.rs --key-tmp=key.tmp");
        const auto tasks = parse_manifest(manifest);
        const bool has_encrypted = std::any_of(tasks.begin(), tasks.end(),
                                               [](const Task& t) { return t.encrypt; });

        std::array<unsigned char, KEY_SIZE> key{};
        if (has_encrypted) {
            require(!key_out.empty() && !key_tmp.empty(),
                    "encrypted tasks require --key-out and --key-tmp");
            key = random_key();
            if (!key_tmp.parent_path().empty()) fs::create_directories(key_tmp.parent_path());
            {
                std::ofstream out(key_tmp, std::ios::binary | std::ios::trunc);
                require(out.good(), "cannot create temporary key");
                out.write(reinterpret_cast<const char*>(key.data()),
                           static_cast<std::streamsize>(key.size()));
                require(out.good(), "cannot write temporary key");
            }
            emit_rust_key(key_out, key);
        } else if (!key_out.empty()) {
            std::error_code ec;
            fs::remove(key_out, ec);
        }

        for (const auto& task : tasks)
            process_task(task, task.encrypt ? &key : nullptr);

        if (has_encrypted) OPENSSL_cleanse(key.data(), key.size());
        std::error_code ec;
        if (!key_tmp.empty()) fs::remove(key_tmp, ec);
        return 0;
    } catch (const std::exception& e) {
        std::cerr << "resource packer error: " << e.what() << "\n";
        return 1;
    }
}
